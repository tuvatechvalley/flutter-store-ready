// Google Play release readiness audit (Flutter, Expo, React Native, Native
// Android).
//
//   dart run <skill>/scripts/play_readiness.dart [project_dir] [--aab <path>] [--last-version-code <n>]
//                                     [--report <path>] [--json <path>] [--no-fail] [--ci]
//
// Inspects the Android project or Expo configuration (signing, keystore, ids,
// SDK levels, manifest, permissions, 16 KB support, built bundle) and writes a
// Markdown report. Exit code 1 when any check FAILS, so it can gate CI and
// release scripts.
//
// Policy thresholds come from store_policies.json next to this script.
// Secrets are never printed: passwords are only passed to keytool through
// environment variables, not through the command line.
//
// Uses only dart:convert and dart:io so it runs anywhere Dart is installed.
// ignore_for_file: avoid_print

import 'dart:convert';
import 'dart:io';

import 'project_detector.dart';
import 'store_policies.dart';

enum Status { pass, warn, fail, manual }

final class Check {
  Check(this.area, this.title, this.status, this.detail, [this.fix]);

  final String area;
  final String title;
  final Status status;
  final String detail;
  final String? fix;

  Map<String, Object?> toJson() => {
    'area': area,
    'title': title,
    'status': status.name,
    'detail': detail,
    'fix': fix,
  };
}

final _checks = <Check>[];

void _add(String area, String title, Status s, String detail, [String? fix]) =>
    _checks.add(Check(area, title, s, detail, fix));

late final String _root;
late final ProjectProfile _profile;
late final GooglePlayPolicies _policy;

/// `--ci`: signing material cannot exist on a CI machine, so a missing
/// key.properties is reported as a warning instead of blocking.
bool _ci = false;

Future<void> main(List<String> args) async {
  String? opt(String name) {
    final i = args.indexOf(name);
    return i >= 0 && i + 1 < args.length ? args[i + 1] : null;
  }

  const valueFlags = {'--aab', '--last-version-code', '--report', '--json'};
  final positional = <String>[];
  for (var i = 0; i < args.length; i++) {
    if (valueFlags.contains(args[i])) {
      i++;
    } else if (!args[i].startsWith('--')) {
      positional.add(args[i]);
    }
  }
  _root = Directory(
    positional.isEmpty ? Directory.current.path : positional.first,
  ).resolveSymbolicLinksSync();
  _policy = StorePolicies.load().googlePlay;
  _profile = ProjectProfile.detect(_root);

  final reportPath = opt('--report') ?? 'build/reports/play_readiness.md';
  final jsonPath = opt('--json');
  final lastVersionCode = int.tryParse(opt('--last-version-code') ?? '');
  final defaultAab = _profile.androidRoot == '.'
      ? 'app/build/outputs/bundle/release/app-release.aab'
      : 'build/app/outputs/bundle/release/app-release.aab';
  final aabPath = opt('--aab') ?? defaultAab;

  _ci = args.contains('--ci');
  if (args.contains('--manual-only')) {
    _manualChecks('');
    _finish(reportPath, jsonPath, args.contains('--no-fail'));
    return;
  }

  // Expo managed workflow without a native android/ directory.
  if (_profile.isExpo && _profile.androidAppDir == null) {
    _checkExpoAndroid(lastVersionCode);
    _checkPluginsAndKeys('', null);
    _checkSecretsInRepo();
    _manualChecks('');
    _finish(reportPath, jsonPath, args.contains('--no-fail'));
    return;
  }

  if (_profile.androidAppDir == null) {
    _add(
      'Project',
      'android/ folder',
      Status.fail,
      'android/ does not exist.',
      _profile.isFlutter
          ? 'Run `flutter create --platforms=android .` then `harden_platforms.dart` from the flutter-store-ready skill (`tool/flutter_store_ready/` once installed).'
          : 'Add an Android target or configure `expo.android` in app.json.',
    );
    _finish(reportPath, jsonPath, args.contains('--no-fail'));
    return;
  }

  if (_profile.isExpo && _profile.isGitIgnored('android')) {
    _add(
      'Project',
      'Expo prebuild sync',
      Status.warn,
      'android/ exists locally and is git-ignored (generated by `expo prebuild`). Any manual edits in android/ (signing, manifest, R8) are wiped on the next `prebuild --clean` or EAS build unless also configured in app.json / config plugins.',
      'Move permanent Android settings into app.json, expo-build-properties, or a custom Expo config plugin.',
    );
  }

  final gradle = _readGradle();
  final manifestRel = '${_profile.androidAppDir}/src/main/AndroidManifest.xml';
  final manifest = _read(manifestRel) ?? '';
  // The signing file is whatever build.gradle loads: Flutter's convention is
  // key.properties, React Native / Expo projects often use keystore.properties.
  _signingProps = _signingPropsName(gradle);
  final keyPropsPath = _profile.androidRoot == '.'
      ? _signingProps
      : '${_profile.androidRoot}/$_signingProps';
  final keyProps =
      _readProperties(keyPropsPath) ??
      _readProperties('android/$_signingProps');

  await _checkSigning(gradle, keyProps);
  _checkIdentity(gradle, manifest, lastVersionCode);
  _checkSdkLevels(gradle);
  _checkManifest(manifest);
  final merged = _mergedManifest();
  _checkPermissions(merged ?? manifest, merged: merged != null);
  _checkPluginsAndKeys(manifest, merged);
  _check16Kb(gradle);
  await _checkBundle(aabPath);
  _checkSecretsInRepo();
  _manualChecks(manifest);

  _finish(reportPath, jsonPath, args.contains('--no-fail'));
}

// ------------------------------------------------------------ Expo managed

void _checkExpoAndroid(int? lastVersionCode) {
  final android = _profile.expoAndroid ?? const <String, Object?>{};
  final eas = _readJsonMap('$_root/eas.json');
  final hasEasProd =
      eas['build'] is Map && (eas['build']! as Map).containsKey('production');
  _add(
    'Signing',
    'EAS / release signing',
    hasEasProd ? Status.pass : (_ci ? Status.warn : Status.manual),
    hasEasProd
        ? 'eas.json defines a production build profile (EAS manages the upload keystore unless local credentials are configured).'
        : 'Managed Expo project with no native android/ folder and no eas.json production profile.',
    hasEasProd
        ? null
        : 'Configure `eas.json` with a `production` profile (`eas build --platform android`) or run `npx expo prebuild` and configure `android/key.properties`.',
  );

  final pkg = '${android['package'] ?? ''}'.trim();
  if (pkg.isEmpty) {
    _add(
      'App identity',
      'applicationId',
      Status.fail,
      '`expo.android.package` is missing in app.json.',
      'Set a permanent reverse-domain id (e.g. "com.yourcompany.app") in app.json -> expo.android.package.',
    );
  } else if (pkg.startsWith('com.example') || pkg.startsWith('com.anonymous')) {
    _add(
      'App identity',
      'applicationId',
      Status.fail,
      '"$pkg" — Play rejects placeholder package names and applicationId can never be changed after release.',
      'Choose a permanent reverse-domain id you own in app.json -> expo.android.package.',
    );
  } else {
    _add(
      'App identity',
      'applicationId',
      Status.pass,
      '"$pkg" (from app.json).',
    );
  }

  final verName = '${_profile.expoConfig['version'] ?? ''}'.trim();
  final rawCode = android['versionCode'];
  final code = rawCode is int ? rawCode : int.tryParse('${rawCode ?? ''}');
  if (verName.isEmpty) {
    _add(
      'App identity',
      'Version',
      Status.fail,
      '`expo.version` is missing in app.json.',
    );
  } else if (code == null || code < 1) {
    _add(
      'App identity',
      'versionCode',
      hasEasProd ? Status.warn : Status.fail,
      'No `expo.android.versionCode` in app.json${hasEasProd ? ' (acceptable only if `autoIncrement` / remote appVersionSource is enabled in eas.json)' : ''}.',
      'Set `expo.android.versionCode` >= 1 in app.json (or enable remote autoIncrement in eas.json).',
    );
  } else if (lastVersionCode != null && code <= lastVersionCode) {
    _add(
      'App identity',
      'versionCode',
      Status.fail,
      'versionCode $code is not greater than the last upload ($lastVersionCode).',
      'Bump `expo.android.versionCode` in app.json.',
    );
  } else {
    _add(
      'App identity',
      'versionCode',
      lastVersionCode == null ? Status.warn : Status.pass,
      'versionName $verName, versionCode $code.'
          '${lastVersionCode == null ? ' Must be higher than every previous upload (pass --last-version-code to verify).' : ''}',
    );
  }

  final appName = '${_profile.expoConfig['name'] ?? ''}'.trim();
  if (RegExp(
    r'\b(beta|demo|test|dev|staging)\b',
    caseSensitive: false,
  ).hasMatch(appName)) {
    _add(
      'App identity',
      'App name is a release name',
      Status.warn,
      '"$appName" contains a word that marks an unfinished build.',
      'Use the final name in app.json -> expo.name.',
    );
  }

  // Permissions in app.json (`expo.android.permissions` minus `blockedPermissions`)
  final blocked = {
    if (android['blockedPermissions'] case final List<Object?> b)
      for (final p in b.whereType<String>()) p.split('.').last,
  };
  final perms = {
    if (android['permissions'] case final List<Object?> p)
      for (final item in p.whereType<String>()) item.split('.').last,
  }..removeAll(blocked);

  final fakeManifest = perms
      .map((p) => '<uses-permission android:name="android.permission.$p"/>')
      .join('\n');
  _checkPermissions(fakeManifest, merged: false);

  // Check expo-build-properties for targetSdkVersion / usesCleartextTraffic.
  final buildProps = _expoBuildPropertiesSection('android');
  final target = buildProps['targetSdkVersion'];
  final targetInt = target is int ? target : int.tryParse('${target ?? ''}');
  if (targetInt != null) {
    final req = _policy.requiredTargetSdk;
    _add(
      'SDK levels',
      'targetSdk',
      targetInt >= req ? Status.pass : Status.fail,
      'targetSdkVersion $targetInt in expo-build-properties (Play requires >= $req).',
      targetInt >= req
          ? null
          : 'Raise android.targetSdkVersion to $req in expo-build-properties (or upgrade the Expo SDK).',
    );
  } else {
    _add(
      'SDK levels',
      'targetSdk',
      Status.manual,
      'Managed by the Expo SDK (verify the built AAB targets API >= ${_policy.requiredTargetSdk}, ${_policy.requiredTargetSdkAndroidName}).',
      'Check Play Console > App bundle explorer after building, or pin targetSdkVersion via expo-build-properties.',
    );
  }
  if (buildProps['usesCleartextTraffic'] == true) {
    _add(
      'Manifest & security',
      'Cleartext HTTP',
      Status.fail,
      '`usesCleartextTraffic: true` in expo-build-properties allows unencrypted HTTP in release.',
      'Remove usesCleartextTraffic: true for production builds.',
    );
  }
}

Map<String, Object?> _expoBuildPropertiesSection(String platform) {
  final plugins = _profile.expoConfig['plugins'];
  if (plugins is! List) return const {};
  for (final entry in plugins) {
    if (entry is List &&
        entry.length >= 2 &&
        entry.first == 'expo-build-properties' &&
        entry[1] is Map) {
      final cfg = (entry[1]! as Map).cast<String, Object?>();
      final sub = cfg[platform];
      if (sub is Map) return sub.cast<String, Object?>();
    }
  }
  return const {};
}

// ------------------------------------------------------------------ signing

/// Name of the signing properties file `build.gradle(.kts)` loads (Flutter:
/// key.properties; React Native / Expo templates: keystore.properties …).
String _signingProps = 'key.properties';

String _signingPropsName(String gradle) {
  for (final m in RegExp(
    r'''file\(\s*["']([\w./-]+\.properties)["']\s*\)''',
  ).allMatches(gradle)) {
    final name = m.group(1)!.split('/').last;
    if (name != 'gradle.properties' && name != 'local.properties') {
      return name;
    }
  }
  return 'key.properties';
}

Future<void> _checkSigning(String gradle, Map<String, String>? props) async {
  const area = 'Signing';
  // Expo / React Native apps built with EAS keep the upload key in EAS
  // credentials: no properties file is expected on this machine.
  final eas = _profile.isExpo && File('$_root/eas.json').existsSync();
  if (props == null) {
    _add(
      area,
      'android/$_signingProps',
      _ci || eas ? Status.warn : Status.fail,
      _ci
          ? 'Missing (expected on CI: the upload key lives on the release machine). Not checked: keystore, alias, passwords.'
          : eas
          ? 'Not on this machine. With EAS Build the upload key is kept in EAS credentials (`eas credentials`) — confirm the production profile uses it; local release builds would be debug-signed.'
          : 'Missing. Release builds would be signed with the debug key and Play rejects them.',
      'Create an upload key and android/$_signingProps (see GOOGLE-PLAY-RELEASE.md in the flutter-store-ready skill).',
    );
  } else {
    final missing = [
      'storeFile',
      'storePassword',
      'keyAlias',
      'keyPassword',
    ].where((k) => (props[k] ?? '').isEmpty).toList();
    _add(
      area,
      '$_signingProps fields',
      missing.isEmpty ? Status.pass : Status.fail,
      missing.isEmpty
          ? 'storeFile, storePassword, keyAlias, keyPassword are set.'
          : 'Missing: ${missing.join(', ')}',
    );
  }

  final usesKeyProps =
      gradle.contains(_signingProps) || gradle.contains('signingConfigs');
  final hasKeyPropsRef = gradle.contains(_signingProps);
  // Only look at buildTypes: signingConfigs also has a `release { }` block.
  final buildTypesAt = gradle.indexOf('buildTypes');
  final buildTypes = buildTypesAt < 0 ? gradle : gradle.substring(buildTypesAt);
  final alwaysDebug =
      RegExp(
        r'signingConfig\s*=?\s*signingConfigs\.(?:getByName\("debug"\)|debug)\s*$',
        multiLine: true,
      ).hasMatch(buildTypes) &&
      !buildTypes.contains('getByName("release")') &&
      !buildTypes.contains('signingConfigs.release');
  final explicitReleaseConfig =
      !_profile.isFlutter &&
      usesKeyProps &&
      (buildTypes.contains('getByName("release")') ||
          buildTypes.contains('signingConfigs.release'));
  if (alwaysDebug || (!hasKeyPropsRef && !explicitReleaseConfig)) {
    _add(
      area,
      'Release signingConfig',
      Status.fail,
      'The release build type is signed with the DEBUG key.',
      'Run `harden_platforms.dart` from the flutter-store-ready skill (`tool/flutter_store_ready/` once installed) or configure signingConfigs.release.',
    );
  } else {
    _add(
      area,
      'Release signingConfig',
      Status.pass,
      'Release uses signingConfigs "release".',
    );
  }

  if (props == null) return;
  final storeFile = (props['storeFile'] ?? '').replaceAll(r'\\', r'\');
  final appDir = _profile.androidAppDir ?? 'android/app';
  final andRoot = _profile.androidRoot ?? 'android';
  final candidates = [
    File(storeFile),
    File('$_root/$appDir/$storeFile'),
    File('$_root/$andRoot/$storeFile'),
  ];
  final keystore = candidates
      .where((f) => storeFile.isNotEmpty && f.existsSync())
      .firstOrNull;
  if (keystore == null) {
    _add(
      area,
      'Keystore file',
      Status.fail,
      'storeFile "$storeFile" not found (relative to $appDir).',
      'Point storeFile to your upload keystore (.jks). Keep it OUTSIDE the repository.',
    );
    return;
  }
  final insideRepo = keystore.absolute.path.toLowerCase().startsWith(
    _root.toLowerCase(),
  );
  _add(
    area,
    'Keystore file',
    insideRepo ? Status.warn : Status.pass,
    insideRepo
        ? 'Found inside the project folder (${_rel(keystore.path)}). Easy to leak or delete.'
        : 'Found outside the repository.',
    insideRepo
        ? 'Move it outside the repo (e.g. ~/keys/) and back it up in a password manager.'
        : null,
  );

  await _inspectKeystore(keystore.path, props);
}

Future<void> _inspectKeystore(String path, Map<String, String> props) async {
  const area = 'Signing';
  final keytool = await _which('keytool');
  if (keytool == null) {
    _add(
      area,
      'Keystore contents',
      Status.warn,
      'keytool not found (install a JDK) - could not open the keystore.',
    );
    return;
  }
  final result = await Process.run(
    keytool,
    [
      '-list',
      '-v',
      '-keystore',
      path,
      '-alias',
      props['keyAlias'] ?? '',
      '-storepass:env',
      'PLAY_AUDIT_STOREPASS',
    ],
    environment: {'PLAY_AUDIT_STOREPASS': props['storePassword'] ?? ''},
  );
  final out = '${result.stdout}\n${result.stderr}';
  if (result.exitCode != 0) {
    final reason =
        out.contains('password was incorrect') ||
            out.contains('Keystore was tampered')
        ? 'storePassword is wrong.'
        : out.contains('does not exist')
        ? 'Alias "${props['keyAlias']}" does not exist in the keystore.'
        : 'keytool could not read the keystore.';
    _add(
      area,
      'Keystore contents',
      Status.fail,
      reason,
      'Fix key.properties so it matches the keystore.',
    );
    return;
  }
  final until = RegExp(r'until:\s*(.+)').firstMatch(out)?.group(1)?.trim();
  final owner =
      RegExp(r'Owner:\s*(.+)').firstMatch(out)?.group(1)?.trim() ?? '';
  final algo =
      RegExp(r'Signature algorithm name:\s*(\S+)').firstMatch(out)?.group(1) ??
      '?';
  final sha256 = RegExp(r'SHA256:\s*(\S+)').firstMatch(out)?.group(1) ?? '?';
  if (owner.contains('Android Debug')) {
    _add(
      area,
      'Upload key',
      Status.fail,
      'The keystore contains the Android DEBUG certificate.',
      'Generate a real upload key with keytool -genkeypair (GOOGLE-PLAY-RELEASE.md in the flutter-store-ready skill).',
    );
  } else {
    _add(
      area,
      'Upload key',
      Status.pass,
      'Alias "${props['keyAlias']}" OK. Algorithm $algo. SHA-256 $sha256. Valid until $until.\n'
          'Register this SHA-256 as the *upload* certificate if Play App Signing asks for it.',
    );
  }
  final year = int.tryParse(
    RegExp(r'(\d{4})\s*$').firstMatch(until ?? '')?.group(1) ?? '',
  );
  if (year != null &&
      year < DateTime.now().year + _policy.minKeyValidityYears) {
    _add(
      area,
      'Key validity',
      Status.warn,
      'Certificate expires in $year.',
      'Use -validity 10000 (≈27 years) when creating upload keys.',
    );
  }
}

// ----------------------------------------------------------------- identity

void _checkIdentity(String gradle, String manifest, int? lastVersionCode) {
  const area = 'App identity';
  final appId = RegExp(
    r'applicationId\s*=?\s*["\x27]([^"\x27]+)["\x27]',
  ).firstMatch(gradle)?.group(1);
  if (appId == null) {
    _add(
      area,
      'applicationId',
      Status.fail,
      'Not found in ${_profile.androidAppDir ?? 'android/app'}/build.gradle(.kts).',
    );
  } else if (appId.startsWith('com.example') ||
      appId.startsWith('com.android') ||
      appId.startsWith('com.anonymous') ||
      appId.contains('flutter')) {
    _add(
      area,
      'applicationId',
      Status.fail,
      '"$appId" — Play rejects com.example.* and it can never be changed after release.',
      'Choose a permanent reverse-domain id you own, e.g. com.yourcompany.app (also update namespace and the Kotlin package).',
    );
  } else {
    _add(
      area,
      'applicationId',
      Status.pass,
      '"$appId" (permanent after first upload).',
    );
  }

  _checkAndroidVersioning(gradle, lastVersionCode);

  final label =
      RegExp(r'android:label="([^"]*)"').firstMatch(manifest)?.group(1) ?? '';
  final resolvedLabel = label.startsWith('@string/')
      ? (_androidStringResource(label.substring('@string/'.length)) ?? label)
      : label;
  final looksDefault =
      resolvedLabel.isEmpty || RegExp(r'^[a-z0-9_]+$').hasMatch(resolvedLabel);
  _add(
    area,
    'App name (android:label)',
    looksDefault ? Status.warn : Status.pass,
    looksDefault
        ? '"$resolvedLabel" looks like the package name, not a user-facing name.'
        : '"$resolvedLabel"',
    looksDefault
        ? 'Set android:label to the real app name (or a @string resource for localization).'
        : null,
  );
  if (RegExp(
    r'\b(beta|demo|test|dev|staging)\b',
    caseSensitive: false,
  ).hasMatch(resolvedLabel)) {
    _add(
      area,
      'App name is a release name',
      Status.warn,
      '"$resolvedLabel" contains a word that marks an unfinished build. Stores reject "beta" / "demo" / "test" apps on the production track.',
      'Use the final name (keep the dev label in a debug flavor only).',
    );
  }

  final appDir = _profile.androidAppDir ?? 'android/app';
  final icon = File(
    '$_root/$appDir/src/main/res/mipmap-xxxhdpi/ic_launcher.png',
  );
  if (icon.existsSync()) {
    final isDefault = _policy.defaultIconMd5.contains(_md5(icon));
    _add(
      area,
      'Launcher icon',
      isDefault ? Status.fail : Status.pass,
      isDefault ? 'Still the default Flutter icon.' : 'Custom icon present.',
      isDefault
          ? 'Generate icons (e.g. flutter_launcher_icons) incl. adaptive + monochrome.'
          : null,
    );
  }
}

void _checkAndroidVersioning(String gradle, int? lastVersionCode) {
  const area = 'App identity';
  if (_profile.isFlutter) {
    final pubspec = _read('pubspec.yaml') ?? '';
    final version = RegExp(
      r'^version:\s*([0-9]+\.[0-9]+\.[0-9]+)(?:\+([0-9]+))?\s*$',
      multiLine: true,
    ).firstMatch(pubspec);
    if (version == null) {
      _add(
        area,
        'Version',
        Status.fail,
        'pubspec.yaml has no valid `version: x.y.z+build`.',
      );
      return;
    }
    final code = int.tryParse(version.group(2) ?? '');
    _reportVersionCode(
      version.group(1)!,
      code,
      lastVersionCode,
      'pubspec.yaml',
    );
    return;
  }

  // Non-Flutter (React Native, Expo prebuild, Native Android): read Gradle or app.json.
  final gradleVerName = RegExp(
    r'versionName\s*=?\s*["\x27]([^"\x27]+)["\x27]',
  ).firstMatch(gradle)?.group(1);
  final gradleVerCode = int.tryParse(
    RegExp(r'versionCode\s*=?\s*(\d+)').firstMatch(gradle)?.group(1) ?? '',
  );
  final verName =
      gradleVerName ??
      '${_profile.expoConfig['version'] ?? _profile.packageJson['version'] ?? ''}'
          .trim();
  final rawExpoCode = _profile.expoAndroid?['versionCode'];
  final code =
      gradleVerCode ??
      (rawExpoCode is int ? rawExpoCode : int.tryParse('${rawExpoCode ?? ''}'));
  if (verName.isEmpty) {
    _add(
      area,
      'Version',
      Status.fail,
      'versionName not found in build.gradle(.kts) or app.json.',
    );
    return;
  }
  _reportVersionCode(verName, code, lastVersionCode, 'build.gradle(.kts)');
}

void _reportVersionCode(
  String versionName,
  int? code,
  int? lastVersionCode,
  String sourceFile,
) {
  const area = 'App identity';
  if (code == null || code < 1) {
    _add(
      area,
      'versionCode',
      Status.fail,
      _profile.isFlutter
          ? 'Missing build number (+N) in pubspec version.'
          : 'Missing or invalid versionCode in $sourceFile.',
    );
  } else if (lastVersionCode != null && code <= lastVersionCode) {
    _add(
      area,
      'versionCode',
      Status.fail,
      'versionCode $code is not greater than the last upload ($lastVersionCode).',
      _profile.isFlutter
          ? 'Bump the +N part of `version:` in pubspec.yaml.'
          : 'Bump versionCode in $sourceFile.',
    );
  } else {
    _add(
      area,
      'versionCode',
      lastVersionCode == null ? Status.warn : Status.pass,
      'versionName $versionName, versionCode $code.'
          '${lastVersionCode == null ? ' Must be higher than every previous upload (pass --last-version-code to verify).' : ''}',
    );
  }
  if (code != null && code > 2100000000) {
    _add(
      area,
      'versionCode range',
      Status.fail,
      'versionCode must be <= 2100000000.',
    );
  }
}

String? _androidStringResource(String key) {
  final appDir = _profile.androidAppDir ?? 'android/app';
  final stringsXml = _read('$appDir/src/main/res/values/strings.xml');
