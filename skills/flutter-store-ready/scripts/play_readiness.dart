      if (File('$_root/$manifestFile').existsSync() &&
          File('$_root/$manifestFile').lastModifiedSync().isAfter(built))
        File('$_root/$manifestFile'),
  ];
  final day = built.toIso8601String().substring(0, 10);
  _add(
    area,
