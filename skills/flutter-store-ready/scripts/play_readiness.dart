// ---------------------------------------------------------------- SDK level

void _checkSdkLevels(String gradle) {
  const area = 'SDK levels';
  final flutterDefaults = _profile.isFlutter
      ? _flutterGradleDefaults()
      : const <String, int>{};
  final rootGradle = _profile.androidRoot != null
      ? (_read('${_profile.androidRoot}/build.gradle.kts') ??
            _read('${_profile.androidRoot}/build.gradle') ??
            '')
      : '';
  int? resolve(String key, String flutterKey, String rootPropKey) {
    final m = RegExp('$key\\s*=?\\s*(\\S+)').firstMatch(gradle)?.group(1);
    if (m == null) return null;
    final direct = int.tryParse(m);
    if (direct != null) return direct;
    if (m.contains('flutter.')) return flutterDefaults[flutterKey];
    final ext = RegExp(
      '$rootPropKey\\s*=?\\s*(\\d+)',
    ).firstMatch(rootGradle)?.group(1);
    return int.tryParse(ext ?? '');
  }

  final req = _policy.requiredTargetSdk;
  final androidName = _policy.requiredTargetSdkAndroidName;
  final target = resolve(
    'targetSdk(?:Version)?',
    'targetSdkVersion',
    'targetSdkVersion',
  );
  if (target == null) {
    _add(
      area,
      'targetSdk',
      Status.warn,
      'Could not resolve targetSdk${_profile.isFlutter ? ' (Flutter SDK not found to read its default)' : ''}.',
      'Ensure targetSdk >= $req ($androidName). Check with release bundle output or Play Console.',
    );
  } else {
    _add(
      area,
      'targetSdk',
      target >= req ? Status.pass : Status.fail,
      'targetSdk $target (Play requires >= $req for new apps and updates).',
      target >= req
          ? null
          : 'Set targetSdk = $req and test the $androidName behavior changes.',
    );
  }
  final compile = resolve(
    'compileSdk(?:Version)?',
    'compileSdkVersion',
    'compileSdkVersion',
  );
  if (compile != null && target != null && compile < target) {
    _add(
      area,
      'compileSdk',
      Status.fail,
      'compileSdk $compile < targetSdk $target.',
    );
  }
  final min = resolve('minSdk(?:Version)?', 'minSdkVersion', 'minSdkVersion');
  if (min != null) {
    _add(
      area,
      'minSdk',
      min >= _policy.minSupportedSdk ? Status.pass : Status.warn,
      'minSdk $min${min < _policy.recommendedMinSdk ? ' (recommended default is ${_policy.recommendedMinSdk}; older devices need extra testing)' : ''}.',
    );
  }
}

