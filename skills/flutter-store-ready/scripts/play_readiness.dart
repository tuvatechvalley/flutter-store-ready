// ----------------------------------------------------------------- secrets

void _checkSecretsInRepo() {
  const area = 'Secrets';
  final ProcessResult git;
  try {
    git = Process.runSync('git', ['ls-files'], workingDirectory: _root);
  } on ProcessException {
    return;
  }
  if (git.exitCode != 0) {
    _add(
      area,
      'Tracked secrets',
      Status.warn,
      'Not a git repository; could not check tracked files.',
    );
    return;
  }
  final tracked = const LineSplitter().convert('${git.stdout}');
  final leaked = tracked
      .where(
        (f) =>
            f.endsWith('key.properties') ||
            f.endsWith('.jks') ||
            f.endsWith('.keystore') ||
            f.endsWith('.p12') ||
            f.endsWith('.pem') ||
            f.endsWith('google-services.json.secret') ||
            RegExp(r'(^|/)\.env(\.|$)').hasMatch(f) &&
                !f.endsWith('.env.example') ||
            f.endsWith('.local.json') ||
            f == 'config/prod.json',
      )
      .toList();
  _add(
    area,
    'Keystore / key.properties not in git',
    leaked.isEmpty ? Status.pass : Status.fail,
    leaked.isEmpty
        ? 'No signing secrets are tracked.'
        : 'Tracked secret files: ${leaked.join(', ')}',
    leaked.isEmpty
        ? null
        : 'git rm --cached <file>, add to .gitignore, and ROTATE the key/passwords (history keeps them).',
  );
  final andRoot = _profile.androidRoot ?? 'android';
  final prefix = andRoot == '.' ? '' : '$andRoot/';
  final notIgnored = [
    for (final path in ['${prefix}key.properties', '${prefix}upload.jks'])
      if (Process.runSync('git', [
            'check-ignore',
            '-q',
            path,
          ], workingDirectory: _root).exitCode !=
          0)
        path,
  ];
  if (notIgnored.isNotEmpty) {
    _add(
      area,
      '.gitignore',
      Status.warn,
      'Not git-ignored: ${notIgnored.join(', ')} (a keystore placed there would be committed by `git add .`).',
      'Run `harden_platforms.dart` from the flutter-store-ready skill (`tool/flutter_store_ready/` once installed).',
    );
  }
}

